नवीनीकरण() {
    if command -v pkg &> /dev/null; then
        pkg update && pkg upgrade -y
    elif command -v apt &> /dev/null; then
        sudo apt update && sudo apt upgrade -y
    fi
}

संस्थापन() {
    if command -v pkg &> /dev/null; then
        pkg install -y "$@"
    elif command -v apt &> /dev/null; then
        sudo apt install -y "$@"
    fi
}

उपकरण_निष्कासन() {
    if command -v pkg &> /dev/null; then
        pkg uninstall -y "$@"
    elif command -v apt &> /dev/null; then
        sudo apt remove -y "$@"
    fi
}

उपकरण_अन्वेषण() {
    if command -v pkg &> /dev/null; then
        pkg search "$@"
    elif command -v apt &> /dev/null; then
        apt search "$@"
    fi
}

