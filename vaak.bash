#!/usr/bin/env bash
# ==============================================================================
# परियोजना : वाक्-शेल (Vaak-Shell)
# विवरण   : लिनक्स एवं टर्मक्स हेतु देवनागरी कमांड लाइन इंटरफ़ेस
# ==============================================================================

# यूनीकोड विन्यास (टर्मक्स व लिनक्स दोनों में सुरक्षित)
export LANG=C.UTF-8
export LC_ALL=C.UTF-8

# ------------------------------------------------------------------------------
# १. संचिका एवं संदर्शिका प्रबंधन (File & Directory Operations)
# ------------------------------------------------------------------------------
alias सूची="ls --color=auto"
alias सूची_विस्तार="ls -lah --color=auto"
alias वर्तमान="pwd"
alias साफ़="clear"
alias बनाओ="mkdir -p"
alias हटाओ="rm -ri"
alias बलपूर्वक_हटाओ="rm -rf"
alias प्रतिलिपि="cp -r"
alias बदलो="mv"
alias पढ़ो="cat"
alias शीर्ष="head -n 20"
alias अंत="tail -n 20"
alias खोजो_फ़ाइल="find . -name"
alias खोजो_शब्द="grep -rnw . -e"
alias बाहर="exit"
alias बंद="exit"

# संदर्शिका नेविगेशन फलन
जाओ() {
    cd "$1" && ls --color=auto
}
alias पीछे="cd .. && ls --color=auto"

# स्मार्ट स्क्रीन साफ़ या फ़ाइल विलोपन
मिटाओ() {
    if [ $# -eq 0 ]; then
        clear
    else
        rm -ri "$@"
    fi
}

# ------------------------------------------------------------------------------
# २. नेटवर्क एवं डाउनलोड प्रबंधन (Network & Retrieval)
# ------------------------------------------------------------------------------
alias डाउनलोड="curl -O -L"
alias डाउनलोड_नाम="curl -L -o"
alias जाल_जाँच="ping -c 4 8.8.8.8"
alias मेरा_आईपी="curl -s ifconfig.me && echo"

# ------------------------------------------------------------------------------
# ३. संपीड़न एवं अभिलेखागार (Archive & Compression)
# ------------------------------------------------------------------------------
alias ज़िप_खोलो="unzip"
alias ज़िप_बाँधो="zip -r"
alias टार_खोलो="tar -xvf"
alias टार_बाँधो="tar -cvf"
alias टार_जीज़िप_खोलो="tar -xvzf"

# ------------------------------------------------------------------------------
# ४. सिस्टम संसाधन एवं प्रक्रिया प्रबंधन (System Resources & Processes)
# ------------------------------------------------------------------------------
alias प्रक्रियाएँ="ps aux"
alias मारो="kill -9"
alias स्मृति="free -h"
alias डिस्क_स्थान="df -h"
alias फ़ोल्डर_भार="du -sh *"

# ------------------------------------------------------------------------------
# ५. सुरक्षा एवं अनुमति (Permissions & Security)
# ------------------------------------------------------------------------------
alias निष्पादन_अनुमति="chmod +x"
alias पूर्ण_अनुमति="chmod 777"
alias स्वामी_बदलो="chown -R"

# ------------------------------------------------------------------------------
# ६. पैकेज प्रबंधन (टर्मक्स + लिनक्स दोनों के लिए स्मार्ट फलन)
# ------------------------------------------------------------------------------
अद्यतन() {
    if command -v pkg &> /dev/null; then
        pkg update && pkg upgrade -y
    elif command -v apt &> /dev/null; then
        sudo apt update && sudo apt upgrade -y
    elif command -v pacman &> /dev/null; then
        sudo pacman -Syu --noconfirm
    fi
}

स्थापित_करो() {
    if command -v pkg &> /dev/null; then
        pkg install -y "$@"
    elif command -v apt &> /dev/null; then
        sudo apt install -y "$@"
    elif command -v pacman &> /dev/null; then
        sudo pacman -S --noconfirm "$@"
    fi
}

निष्कासित_करो() {
    if command -v pkg &> /dev/null; then
        pkg uninstall -y "$@"
    elif command -v apt &> /dev/null; then
        sudo apt remove -y "$@"
    elif command -v pacman &> /dev/null; then
        sudo pacman -R --noconfirm "$@"
    fi
}

ढूँढो_पैकेज() {
    if command -v pkg &> /dev/null; then
        pkg search "$@"
    elif command -v apt &> /dev/null; then
        apt search "$@"
    elif command -v pacman &> /dev/null; then
        pacman -Ss "$@"
    fi
}

# ------------------------------------------------------------------------------
# ७. गिट संस्करण नियंत्रण (Git Sovereign Stack)
# ------------------------------------------------------------------------------
alias गिट_आरंभ="git init"
alias गिट_क्लोन="git clone"
alias गिट_स्थिति="git status"
alias गिट_जोड़ो="git add ."
alias गिट_खींचो="git pull"
alias गिट_भेजो="git push"
alias गिट_इतिहास="git log --oneline --graph --decorate"
alias गिट_शाखा="git branch"
alias गिट_बदलो="git checkout"

# बिना कोट्स के स्पेस वाला मैसेज सपोर्ट करने वाला कमिट फलन
गिट_प्रतिबद्ध() {
    git commit -m "$*"
}

