#!/usr/bin/env bash
# ==============================================================================
# वाक्-शेल (Vaak-Shell) निष्कासन स्क्रिप्ट
# ==============================================================================

echo "[-] वाक्-शेल (Vaak-Shell) हटाया जा रहा है..."

rm -rf "$HOME/.vaak-shell"

if [ -f "$HOME/.bashrc" ]; then
    sed -i '/वाक्-शेल (Vaak-Shell)/d' "$HOME/.bashrc"
    sed -i '/vaak.bash/d' "$HOME/.bashrc"
fi

echo "[✓] वाक्-शेल पूर्णतः निष्कासित हो चुका है।"
echo "[*] परिवर्तनों को लागू करने हेतु 'source ~/.bashrc' चलाएँ।"